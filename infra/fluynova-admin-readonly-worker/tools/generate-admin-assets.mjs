/**
 * FLUYNOVA — herramienta de empaquetado deterministicamente verificable.
 * Convierte los 3 archivos UI en un módulo ESM embebido en el Worker ADMIN,
 * para que no pueda existir un hosting de assets paralelo sin Access.
 *
 * --check: compara bytes y falla CI ante cualquier drift.
 * --write: regenera SOLO el módulo local, sin red ni despliegue.
 */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const files=['dashboard.html','dashboard.css','dashboard.js'];
const output=new URL('../admin-assets.generated.mjs',import.meta.url);
function sha256(data){return createHash('sha256').update(data).digest('hex')}
export async function expectedModule(){
 const strings={},sha={};
 for(const name of files){
  const data=await readFile(new URL(name,root),'utf8');
  if(!data||data.length>65000||data.includes('\0'))
   throw Error('ASSET_INVALID_'+name);
  strings[name]=data;sha[name]=sha256(data);
 }
 const source=[
  '// AUTO-GENERATED by tools/generate-admin-assets.mjs — DO NOT EDIT BY HAND.',
  '// Only use behind verified Cloudflare Access. Does not imply publication.',
  'export const ADMIN_ASSET_HASHES = Object.freeze('+JSON.stringify(sha,null,2)+');',
  'export const ADMIN_ASSETS = Object.freeze('+JSON.stringify(strings,null,2)+');',
  ''
 ].join('\n');
 return source;
}
const action=process.argv[2]||'--check';
if(process.argv[1]?.endsWith('generate-admin-assets.mjs')){
 const generated=await expectedModule();
 if(action==='--write'){
  await writeFile(output,generated,'utf8');
  console.log('ADMIN_ASSETS_GENERATED: files=3, only_local=true');
 }else if(action==='--check'){
  const current=await readFile(output,'utf8').catch(()=>null);
  if(current!==generated)throw Error('ADMIN_ASSETS_OUT_OF_SYNC');
  console.log('ADMIN_ASSETS_IN_SYNC: files=3, checksums=sha256, no_deploy=true');
 }else{
  throw Error('INVALID_COMMAND_USE_CHECK_OR_WRITE');
 }
}
